#!/usr/bin/env node
// Held-out eval generator: 240 scenarios, seed 1337 (training used seed 42).
// Deliberate differences from training data: disjoint payer names, amounts,
// invoice series (H-5xxx vs F-1xxx), Dec 2026 - Feb 2027 due dates (training
// used Sep-Nov 2026), and history phrasing variants. Labels come from the
// documented ladder policy (src/brain/heuristic.js), same as training.
import { writeFileSync } from 'fs';

function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(1337);
const pick = (arr) => arr[Math.floor(rnd() * arr.length)];

// disjoint from the 15 training names
const NAMES = ['Yusuf Rahman', 'Clara Whitfield', 'Dev Patel', 'Ingrid Sorensen', 'Callum Reid',
  'Fatima Al-Sayed', 'George Tanner', 'Priya Nair', 'Viktor Lund', 'Adele Fontaine',
  'Marcus Webb', 'Saoirse Byrne', 'Kenji Mori', 'Lena Novak', 'Ravi Menon',
  'Isla MacLeod', 'Tomas Silva', 'Nadia Hussain', 'Erik Brandt', 'Wren Davies'];
// disjoint amounts from the training set
const AMOUNTS = ['95.00', '175.00', '260.00', '340.00', '520.00', '640.00', '725.00',
  '910.00', '1120.00', '1350.00', '1680.00', '1950.00', '2400.00'];
const DUES = ['2026-12-02', '2026-12-11', '2026-12-19', '2026-12-28', '2027-01-05',
  '2027-01-14', '2027-01-22', '2027-01-30', '2027-02-06', '2027-02-15'];

const DAY_BUCKETS = [
  ...Array.from({ length: 12 }, (_, i) => -(i + 1)),   // not yet due -> wait
  0, 0, 0,                                             // due today -> wait
  ...Array.from({ length: 7 }, (_, i) => i + 1),       // gentle 1-7
  7, 8, 7, 8,                                          // boundary
  ...Array.from({ length: 14 }, (_, i) => i + 8),      // firm 8-21
  21, 22, 21, 22,                                      // boundary
  ...Array.from({ length: 24 }, (_, i) => i + 22),     // final 22-45
];

function toneFor(d) { return d <= 7 ? 'gentle' : d <= 21 ? 'firm' : 'final'; }

function historyFor(days, first, variant) {
  if (days <= 3 || rnd() < 0.4) return [];
  const h = [];
  if (days > 7) {
    h.push(variant % 2 === 0
      ? { action: 'reminded', tone: 'gentle', at: '2027-01-10T09:00:00Z', note: `gentle nudge sent to ${first}` }
      : { action: 'reminded', tone: 'gentle', at: '2027-01-08T15:30:00Z', note: `first chaser emailed to ${first}` });
  }
  if (days > 21 && rnd() < 0.7) {
    h.push({ action: 'reminded', tone: 'firm', at: '2027-01-25T10:00:00Z', note: `firm follow-up sent to ${first}` });
  }
  return h;
}

const scenarios = [];
for (let i = 0; i < 240; i++) {
  const name = pick(NAMES);
  const first = name.split(' ')[0];
  const days = pick(DAY_BUCKETS);
  const status = rnd() < 0.72 ? 'SENT' : rnd() < 0.55 ? 'PAID' : 'DRAFT';
  const chaseable = status === 'SENT' && days > 0;
  const due = pick(DUES);
  const amount = pick(AMOUNTS);
  const history = chaseable ? historyFor(days, first, i) : [];
  const expect = chaseable
    ? { action: 'remind', tone: toneFor(days) }
    : { action: 'wait' };
  scenarios.push({
    id: `H${String(i).padStart(3, '0')}-${chaseable ? toneFor(days) : 'wait'}-${days}d`,
    summary: {
      id: `INV-H${i}`, number: `H-${5000 + i}`, status, payerName: name,
      payerEmail: `${first.toLowerCase().replace(/[^a-z]/g, '')}@example.net`,
      amount, currency: 'GBP', dueDate: due, daysOverdue: days, chaseable,
    },
    history,
    expect,
  });
}
writeFileSync('evals/scenarios_big.json', JSON.stringify({
  description: 'Held-out eval set (seed 1337): disjoint names, amounts, invoice series and due-date months vs training data. Labels from the documented ladder policy. Generated by gen_big_scenarios.js; leak check in evals/leak_check.js.',
  scenarios,
}, null, 2));
console.log('wrote', scenarios.length, 'scenarios');
const dist = {};
for (const s of scenarios) { const k = s.expect.action + (s.expect.tone ? '/' + s.expect.tone : ''); dist[k] = (dist[k] || 0) + 1; }
console.log(dist);
